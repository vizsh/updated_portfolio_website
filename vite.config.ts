import { defineConfig, loadEnv, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { PERSONAL_INFO, PROJECTS_DATA } from './src/data/portfolioData';
import { buildKnowledgeChunks, knowledgeDocument } from './src/data/knowledge';

/**
 * Canonical site origin used for og:url / canonical links.
 * Order: explicit SITE_URL, Vercel's production domain (set automatically at build), fallback.
 */
const SITE_URL = (
  process.env.SITE_URL ||
  (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : '') ||
  'https://updatedportfoliowebsite.vercel.app'
).replace(/\/+$/, '');

interface SharePage {
  /** Output path relative to dist, without the trailing /index.html */
  route: string;
  title: string;
  description: string;
}

const escapeAttr = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const clip = (text: string, max = 200) => (text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`);

/** Rewrite the head of the built index.html for one shareable route. */
function withShareMeta(html: string, page: SharePage): string {
  const title = escapeAttr(page.title);
  const description = escapeAttr(clip(page.description));
  const url = escapeAttr(`${SITE_URL}/${page.route}/`);

  return html
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${title}</title>`)
    .replace(/<meta name="description" content="[^"]*"\s*\/?>/, `<meta name="description" content="${description}" />`)
    .replace(/<meta property="og:title" content="[^"]*"\s*\/?>/, `<meta property="og:title" content="${title}" />`)
    .replace(
      /<meta property="og:description" content="[^"]*"\s*\/?>/,
      `<meta property="og:description" content="${description}" />`
    )
    .replace(
      '</head>',
      [
        `    <link rel="canonical" href="${url}" />`,
        `    <meta property="og:url" content="${url}" />`,
        `    <meta name="twitter:card" content="summary" />`,
        `    <meta name="twitter:title" content="${title}" />`,
        `    <meta name="twitter:description" content="${description}" />`,
        '  </head>'
      ].join('\n')
    );
}

/**
 * Emits dist/projects/<id>/index.html and dist/recruiter/index.html: copies of the
 * SPA shell with route-specific titles and Open Graph tags, so links pasted into
 * LinkedIn / WhatsApp / Slack preview the right project instead of the generic site.
 */
function sharePagesPlugin(): Plugin {
  return {
    name: 'portfolio-share-pages',
    apply: 'build',
    async writeBundle(options) {
      const outDir = options.dir ?? path.resolve('dist');
      const shell = await fs.readFile(path.join(outDir, 'index.html'), 'utf-8');

      const pages: SharePage[] = [
        {
          route: 'recruiter',
          title: `${PERSONAL_INFO.name} | Recruiter Summary`,
          description: `${PERSONAL_INFO.role}. ${PERSONAL_INFO.degree}, ${PERSONAL_INFO.institution} (${PERSONAL_INFO.cgpa}). Featured projects, skills, experience and contact on one page.`
        },
        ...PROJECTS_DATA.map(project => ({
          route: `projects/${project.id}`,
          title: `${project.title} | ${PERSONAL_INFO.name}`,
          description: project.description
        }))
      ];

      await Promise.all(
        pages.map(async page => {
          const dir = path.join(outDir, page.route);
          await fs.mkdir(dir, { recursive: true });
          await fs.writeFile(path.join(dir, 'index.html'), withShareMeta(shell, page), 'utf-8');
        })
      );

      this.info(`share pages: wrote ${pages.length} route-specific HTML files (site: ${SITE_URL})`);
    }
  };
}

/**
 * Writes api/_knowledge.ts (the assistant's portfolio documents) from the same data
 * the site renders, so the serverless function never imports app TypeScript at runtime.
 * Runs on every dev start and build; the generated file is committed as a fallback.
 */
function askKnowledgePlugin(): Plugin {
  return {
    name: 'portfolio-ask-knowledge',
    async buildStart() {
      const chunks = buildKnowledgeChunks();
      const content = [
        '// Generated by vite.config.ts from src/data/knowledge.ts. Do not edit by hand.',
        `export const KNOWLEDGE_IDS: readonly string[] = ${JSON.stringify(chunks.map(c => c.id))};`,
        `export const KNOWLEDGE_DOCUMENT = ${JSON.stringify(knowledgeDocument(chunks))};`,
        ''
      ].join('\n');
      const file = path.resolve('api/_knowledge.ts');
      const current = await fs.readFile(file, 'utf-8').catch(() => '');
      if (current !== content) await fs.writeFile(file, content, 'utf-8');
    }
  };
}

/** Serves api/*.ts Web handlers (GET/POST exports) during `vite dev`, like Vercel does in production. */
function devApiPlugin(): Plugin {
  return {
    name: 'portfolio-dev-api',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        const url = req.url ?? '';
        if (!url.startsWith('/api/ask')) return next();
        try {
          const mod = await server.ssrLoadModule('/api/ask.ts');
          const method = (req.method ?? 'GET').toUpperCase();
          const handler = mod[method] as ((request: Request) => Promise<Response> | Response) | undefined;
          if (typeof handler !== 'function') {
            res.statusCode = 405;
            res.end();
            return;
          }
          const body: Buffer[] = [];
          for await (const chunk of req) body.push(chunk as Buffer);
          const headers = new Headers();
          for (const [key, value] of Object.entries(req.headers)) {
            if (typeof value === 'string') headers.set(key, value);
            else if (Array.isArray(value)) headers.set(key, value.join(', '));
          }
          const response = await handler(
            new Request(`http://${req.headers.host ?? 'localhost'}${url}`, {
              method,
              headers,
              body: method === 'GET' || method === 'HEAD' ? undefined : Buffer.concat(body)
            })
          );
          res.statusCode = response.status;
          response.headers.forEach((value, key) => res.setHeader(key, value));
          res.end(Buffer.from(await response.arrayBuffer()));
        } catch (err) {
          server.config.logger.error(`[dev-api] ${err instanceof Error ? err.stack ?? err.message : String(err)}`);
          res.statusCode = 500;
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'dev_api_error' }));
        }
      });
    }
  };
}

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  // Make server-only secrets from .env.local visible to the dev API (never to the client bundle).
  const env = loadEnv(mode, process.cwd(), '');
  for (const key of ['ANTHROPIC_API_KEY', 'ASK_JEEVESH_MODEL']) {
    if (env[key] && !process.env[key]) process.env[key] = env[key];
  }

  return {
  plugins: [react(), sharePagesPlugin(), askKnowledgePlugin(), devApiPlugin()],
  build: {
    // No manualChunks: grouping three/R3F by hand also pulled React into that group, which
    // forced the 1 MB 3D bundle into the first page load. The lazy imports in App.tsx and
    // RetroDesktop.tsx now decide the split, so the recruiter view loads without it.
    chunkSizeWarningLimit: 1600
  }
  };
});
